/// Default Dark theme preset — this template's neutral, unbranded default.
/// Generated from Material 3's own seed-colour algorithm rather than
/// hand-authored, deliberately: a starter template's default should be
/// replaceable, not a designed identity — see [defaultLightColorScheme] for
/// its light-mode sibling, and `ThemeId.sluggerDark` for a real hand-authored
/// example preset kept from this template's origin project.
final ColorScheme defaultDarkColorScheme = ColorScheme.fromSeed(
  seedColor: Colors.blue,
  brightness: Brightness.dark,
);
